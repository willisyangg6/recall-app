-- Parental consent revocation (age assurance, 2026-10-13).
--
-- When a parent or guardian revokes consent for a teen's use of Lotly, Apple
-- blocks the app from launching and sends an App Store Server Notification
-- of type RESCIND_CONSENT (developer.apple.com/support/age-assurance). The
-- app can do nothing then — it cannot launch — so recall alerts must be
-- stopped HERE, on the server.
--
-- The join key is Apple's appTransactionId (per Apple Account and app; the
-- same across devices, reinstalls and "Reset app and delete my data"). It
-- is sent by the app ONLY for a 13–17 user whom Apple reports as regulated,
-- and ONLY while alerts are on — the only installations a revocation can
-- concern (docs/recall-privacy-program-proposal.md §2.6). It is stored as a
-- keyed hash, never raw:
--
--   push_subscriptions.app_transaction_hmac
--     = hex(HMAC-SHA256(appTransactionId, Vault secret app_transaction_hmac_key))
--
-- The Vault key is generated by this migration on the server and never
-- leaves it: not in git, not in the app, not in the Edge Function (which
-- passes the raw id from Apple's verified notification to the service-role
-- RPC below, where the hashing happens).
--
-- Coverage of the column, with no other function re-bodied:
--   - "Reset app and delete my data", privacy-request deletion and the
--     12-month inactivity purge all run delete_installation_data, which
--     deletes the whole subscription row;
--   - the privacy-request export (20261016000000) emits every
--     push_subscriptions column it does not explicitly redact, so the
--     hash is exported as stored.
--
-- What a revocation does: the matching subscriptions are DISABLED with the
-- reason 'consent_revoked' (the push worker sends only to enabled rows).
-- Nothing is deleted, and no block list is kept: if the parent restores
-- consent, Apple lets the app launch again and the app's own registration
-- upkeep re-enables the row, exactly as after any other disable.
--
-- Replay protection: every RESCIND_CONSENT is recorded by Apple's
-- notificationUUID before it acts, in the same transaction, so a retry, a
-- forwarded duplicate or a re-delivered history record changes nothing.
-- The receipts carry no installation id and no Apple identifier.

-- ── 0. The HMAC key (generated here, held in Vault) ─────────────────────────

create extension if not exists pgcrypto with schema extensions;

select vault.create_secret(
  encode(extensions.gen_random_bytes(32), 'hex'),
  'app_transaction_hmac_key',
  'HMAC key for push_subscriptions.app_transaction_hmac (consent revocation)'
)
where not exists (select 1 from vault.secrets where name = 'app_transaction_hmac_key');

-- ── 1. The mapping column ───────────────────────────────────────────────────

alter table public.push_subscriptions
  add column app_transaction_hmac text
    check (app_transaction_hmac is null or app_transaction_hmac ~ '^[0-9a-f]{64}$');

create index push_subscriptions_app_transaction_hmac_idx
  on public.push_subscriptions (app_transaction_hmac)
  where app_transaction_hmac is not null;

-- ── 2. The hash (server-side only) ──────────────────────────────────────────

create or replace function public.app_transaction_hmac(p_app_transaction_id text)
returns text
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_key text;
begin
  select decrypted_secret into v_key
    from vault.decrypted_secrets
   where name = 'app_transaction_hmac_key';
  if v_key is null then
    -- Never store or match an unkeyed value.
    raise exception 'consent revocation key is not configured';
  end if;
  return encode(extensions.hmac(p_app_transaction_id, v_key, 'sha256'), 'hex');
end;
$$;

revoke execute on function public.app_transaction_hmac(text) from public, anon, authenticated;

-- ── 3. The app's write: set or clear this installation's key ───────────────

create or replace function public.set_push_revocation_key(
  p_installation_id text,
  p_app_transaction_id text
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_updated integer;
begin
  -- Shape validation: this endpoint is reachable with the publishable key.
  if p_installation_id is null
     or p_installation_id !~ '^[A-Za-z0-9-]{16,64}$' then
    raise exception 'invalid installation id';
  end if;
  if p_app_transaction_id is not null
     and p_app_transaction_id !~ '^[A-Za-z0-9-]{1,64}$' then
    raise exception 'invalid app transaction id';
  end if;

  -- Only an existing subscription carries a key: there is nothing to stop
  -- for an installation without alerts, so nothing is stored for it.
  update public.push_subscriptions
     set app_transaction_hmac = case
           when p_app_transaction_id is null then null
           else public.app_transaction_hmac(p_app_transaction_id)
         end
   where installation_id = p_installation_id;
  get diagnostics v_updated = row_count;
  return jsonb_build_object('updated', v_updated > 0);
end;
$$;

revoke execute on function public.set_push_revocation_key(text, text) from public;
grant execute on function public.set_push_revocation_key(text, text) to anon, authenticated;

-- ── 4. Receipts (replay protection) ─────────────────────────────────────────

create table public.app_store_notification_receipts (
  notification_uuid uuid primary key,
  notification_type text not null check (notification_type ~ '^[A-Z_]{1,64}$'),
  environment text not null check (environment in ('Sandbox', 'Production')),
  signed_at timestamptz not null,
  received_at timestamptz not null default now(),
  -- How many subscriptions this notification disabled (diagnostics only).
  disabled_count integer not null default 0
);

alter table public.app_store_notification_receipts enable row level security;
-- No policies, no client grants: written only by the RPC below.
grant select, insert, update, delete on public.app_store_notification_receipts to service_role;

-- ── 5. The Edge Function's write: apply one verified revocation ────────────

create or replace function public.apply_consent_revocation(
  p_notification_uuid uuid,
  p_notification_type text,
  p_environment text,
  p_signed_at timestamptz,
  p_app_transaction_id text
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_hmac text;
  v_disabled integer := 0;
begin
  if p_notification_uuid is null or p_signed_at is null then
    raise exception 'invalid notification';
  end if;
  if p_notification_type is distinct from 'RESCIND_CONSENT' then
    raise exception 'unsupported notification type';
  end if;
  if p_app_transaction_id is null
     or p_app_transaction_id !~ '^[A-Za-z0-9-]{1,64}$' then
    raise exception 'invalid app transaction id';
  end if;
  -- Hash first: a missing key raises before anything is recorded, so the
  -- notification is retried rather than consumed.
  v_hmac := public.app_transaction_hmac(p_app_transaction_id);

  insert into public.app_store_notification_receipts
    (notification_uuid, notification_type, environment, signed_at)
  values
    (p_notification_uuid, p_notification_type, p_environment, p_signed_at)
  on conflict (notification_uuid) do nothing;
  if not found then
    return jsonb_build_object('duplicate', true, 'disabled', 0);
  end if;

  update public.push_subscriptions
     set enabled = false,
         disabled_at = now(),
         disabled_reason = 'consent_revoked'
   where app_transaction_hmac = v_hmac
     and enabled;
  get diagnostics v_disabled = row_count;

  update public.app_store_notification_receipts
     set disabled_count = v_disabled
   where notification_uuid = p_notification_uuid;

  -- Receipts are only for replay protection; Apple's own history reaches
  -- back 180 days, so a year is ample.
  delete from public.app_store_notification_receipts
   where received_at < now() - interval '1 year';

  return jsonb_build_object('duplicate', false, 'disabled', v_disabled);
end;
$$;

revoke execute on function public.apply_consent_revocation(uuid, text, text, timestamptz, text)
  from public, anon, authenticated;
grant execute on function public.apply_consent_revocation(uuid, text, text, timestamptz, text)
  to service_role;
