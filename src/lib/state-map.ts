/**
 * The onboarding States map's rules (P2B7Y): which jurisdiction a tap lands
 * on, how each view and inset is framed at a given width, where each
 * selection mark sits, and what every control is called. Numbers and
 * strings only, so all of it is testable under Node; the component draws it
 * with react-native-svg. A leaf apart from the geometry and the vocabulary.
 *
 * ## Why a map, and why the list stays
 *
 * Most shoppers recognise where they live faster than they can find it in a
 * 52-row list, so Map is the default. A map is also the worst possible
 * control for a screen-reader user and for the smallest jurisdictions, so the
 * searchable list is a first-class alternative over the SAME draft, never a
 * fallback that could drift from it.
 *
 * ## The geometry
 *
 * `state-map-geometry.ts` is generated by scripts/build-state-map.ts from the
 * Census Bureau's 2017 cartographic boundaries (via us-atlas 3.0.1, ISC),
 * vendored under assets/geography-sources/us-atlas/. The contiguous states
 * and the District of Columbia are drawn in d3.geoAlbersUsa's projection;
 * Alaska, Hawaii and Puerto Rico each sit in their own inset box. Nothing is
 * fetched: the map makes no network request of any kind.
 *
 * ## Small jurisdictions
 *
 * The Northeast view enlarges Maine to Maryland about four times, so Rhode
 * Island and Delaware become real targets. The District of Columbia is still
 * a few points across even there, so that view draws it as a round marker at
 * its own interior point, and a tap within `DC_TARGET_RADIUS` of the marker
 * chooses it. A tap that lands on water or on a border, outside every
 * shape, chooses the nearest shape within `NEAR_TOLERANCE` points, which is
 * what makes a coastline or an islet forgiving. The insets are whole-box
 * targets, however small their islands draw. And every jurisdiction is in
 * the list.
 */

