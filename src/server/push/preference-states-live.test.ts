// ── The deployed code keeps working against the expanded database ──────────

test(
  'the CURRENTLY DEPLOYED delivery worker’s exact select still resolves',
  { skip: SKIP },
  async () => {
    const stack = STACK as LocalStack;
    // Byte-for-byte the column list on master today (src/server/push/push-store.ts
    // before P2B7U). If the expand phase had dropped state_code, this 400s and
    // every scheduled push run degrades to "no preferences" until the new
    // bundle ships.
    const legacySelect = 'installation_id,state_code,allergens,retailer_ids,updated_at';
    const response = await fetch(
      `${stack.restUrl}/installation_preferences?select=${legacySelect}`,
      { headers: { apikey: stack.serviceKey, Authorization: `Bearer ${stack.serviceKey}` } },
    );
    const body = await response.text();
    assert.ok(response.ok, `the deployed worker's select broke: ${response.status} ${body}`);
    const rows = JSON.parse(body) as { state_code: string | null }[];
    assert.ok(rows.length > 0, 'precondition: earlier cases wrote rows');

    // And the NEW worker's select, on the same database, in the same state.
    const pluralSelect = 'installation_id,state_codes,allergens,retailer_ids,updated_at';
    const next = await fetch(`${stack.restUrl}/installation_preferences?select=${pluralSelect}`, {
      headers: { apikey: stack.serviceKey, Authorization: `Bearer ${stack.serviceKey}` },
    });
    const nextBody = await next.text();
    assert.ok(next.ok, `the new worker's select broke: ${next.status} ${nextBody}`);
    assert.equal((JSON.parse(nextBody) as unknown[]).length, rows.length);
  },
);

test(
  'the shared implementation is not reachable with the publishable key',
  {
    skip: SKIP,
  },
  async () => {
    const stack = STACK as LocalStack;
    // Only the two wrappers are granted to anon; the impl must not become a
    // third, unvalidated entry point.
    const direct = await rpc(stack, 'apply_installation_preferences', {
      p_installation_id: newInstallationId(),
      p_state_codes: ['CA'],
      p_allergens: [],
      p_retailer_ids: [],
    });
    assert.ok(!direct.ok, 'anon could call the internal implementation');
    // Postgres refuses it, not PostgREST's router: SQLSTATE 42501,
    // insufficient_privilege, which PostgREST surfaces as a 401.
    assert.match(direct.message, /permission denied for function apply_installation_preferences/);
    assert.match(direct.message, /42501/);
  },
);
