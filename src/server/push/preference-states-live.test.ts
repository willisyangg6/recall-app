// ── The delivery-safety horizon ─────────────────────────────────────────────

test('an identical write moves nothing, updated_at included', { skip: SKIP }, async () => {
  const stack = STACK as LocalStack;
  const id = newInstallationId();
  assert.ok((await writePlural(stack, id, ['CA', 'NY'], ['peanut'], ['costco'])).ok);
  const first = await readRow(stack, id);
  assert.ok(first);

  // The same selection, sent in a different order — the app re-syncs at launch.
  assert.ok((await writePlural(stack, id, ['NY', 'CA'], ['peanut'], ['costco'])).ok);
  const second = await readRow(stack, id);
  assert.equal(second?.updated_at, first.updated_at, 'a no-op moved the delivery horizon');

  // And through the legacy path, for a single-jurisdiction row.
  const legacyId = newInstallationId();
  assert.ok((await writeLegacy(stack, legacyId, 'TX')).ok);
  const before = await readRow(stack, legacyId);
  assert.ok((await writeLegacy(stack, legacyId, 'TX')).ok);
  assert.equal((await readRow(stack, legacyId))?.updated_at, before?.updated_at);

  // A REAL change does move it — otherwise the no-op above proves nothing.
  assert.ok((await writePlural(stack, id, ['CA', 'NY', 'MT'], ['peanut'], ['costco'])).ok);
  assert.notEqual((await readRow(stack, id))?.updated_at, first.updated_at);
});

